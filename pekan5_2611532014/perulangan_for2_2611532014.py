#program perulangan for

ulang_2014 = int(input("masukkan jumlah perulangan: "))

print("perulangan ke-0 sampai ke-", ulang_2014-1)
for i_2014 in range(ulang_2014):
    print(i_2014, end=" ")
print()
print("perulangana ke-1 sampai ke-", ulang_2014-1)
for i_2014 in range(1, ulang_2014+1):
    print(i_2014, end=" ")









