nilai_2014 = int(input("inputkan nilai angka = "))

if nilai_2014 >= 81:
    print("A")
elif nilai_2014 >= 70:
    print("B")
elif nilai_2014 >= 60:
    print("C")
elif nilai_2014 >= 50:
    print("D")
else:
    print("E")





























